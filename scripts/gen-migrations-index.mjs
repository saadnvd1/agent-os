#!/usr/bin/env node
// Writes lib/db/migrations.generated.ts: one import per file in
// lib/db/migrations/. The file is not committed (a committed list would be the
// one file every migration PR edits). Runs before dev, start, build, typecheck,
// lint and tests; `--check` writes nothing and exits 1 when it is missing or
// stale (CI).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "lib/db/migrations");
const out = join(root, "lib/db/migrations.generated.ts");

export function render() {
  const names = readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"))
    .map((f) => f.slice(0, -3))
    .sort();
  return [
    "// Generated by scripts/gen-migrations-index.mjs from lib/db/migrations/.",
    "// Not committed and never edited: add a migration by adding a file there.",
    'import type { Migration } from "./migration-types";',
    ...names.map((n, i) => `import m${i} from "./migrations/${n}";`),
    "",
    "export const migrationFiles: Record<string, Migration> = {",
    ...names.map((n, i) => `  "${n}": m${i},`),
    "};",
    "",
  ].join("\n");
}

const next = render();
const current = existsSync(out) ? readFileSync(out, "utf8") : null;
if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error(
      "lib/db/migrations.generated.ts is missing or stale: run `node scripts/gen-migrations-index.mjs`"
    );
    process.exit(1);
  }
} else if (current !== next) {
  writeFileSync(out, next);
}
